import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import ucs2Runtime from 'ajv/dist/runtime/ucs2length.js';
import {readFileSync, mkdirSync, writeFileSync} from 'node:fs';

// Compile at build time: Tauri's CSP forbids Ajv's runtime Function constructor.
const schema = JSON.parse(readFileSync('../contracts/config.schema.json', 'utf8'));
const ajv = new Ajv({strict: true, code: {source: true, esm: true}});
let code = standalone(ajv, ajv.compile(schema));
// Ajv emits this CommonJS runtime helper even in its ESM output.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
if (/\brequire\(/.test(code)) throw Error('Add the new Ajv runtime helper as an ESM import');
mkdirSync('src/generated', {recursive: true});
const helper = `const ucs2length = ${ucs2Runtime.default.toString()};\n`;
writeFileSync('src/generated/config-validator.ts', '// @ts-nocheck\n// Generated by scripts/schema.mjs from contracts/config.schema.json.\n' + helper + code + '\n');
